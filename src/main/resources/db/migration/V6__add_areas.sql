-- 갈곳 V6: 구·시군 지역과 지역별 날씨
-- areas: 지역(시도 전체 2개 + 서울 구 25개 + 경기 시·군 31개). 격자(nx, ny)와 대표 위경도는
--        기상청 단기예보 격자 엑셀(2026-09-30)의 시군구 행. 구가 있는 경기 시 8곳은 시청이 있는 구의 값.
-- area_signgus: 장소(places)에 저장된 (시도, 시군구 코드) -> 지역. 구가 있는 시는 여러 코드가 한 지역으로 이어진다.
-- weather_forecasts: 지역 코드 기준으로 저장하도록 바꾼다. 기존 행은 캐시라서 비우고 다시 받는다.

CREATE TABLE areas (
    area_code     VARCHAR(5)  NOT NULL,
    ldong_regn_cd VARCHAR(5)  NOT NULL,
    area_level    VARCHAR(10) NOT NULL,
    name          VARCHAR(20) NOT NULL,
    nx            INT         NOT NULL,
    ny            INT         NOT NULL,
    lat           DOUBLE      NOT NULL,
    lng           DOUBLE      NOT NULL,
    PRIMARY KEY (area_code),
    KEY idx_areas_region_level (ldong_regn_cd, area_level)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE area_signgus (
    ldong_regn_cd   VARCHAR(5) NOT NULL,
    ldong_signgu_cd VARCHAR(5) NOT NULL,
    area_code       VARCHAR(5) NOT NULL,
    PRIMARY KEY (ldong_regn_cd, ldong_signgu_cd),
    KEY idx_area_signgus_area (area_code),
    CONSTRAINT fk_area_signgus_area FOREIGN KEY (area_code) REFERENCES areas (area_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

